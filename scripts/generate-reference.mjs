import { mkdir, readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const catalog = JSON.parse(await readFile(new URL('src/report-catalog.json', root), 'utf8'));
const reference = new URL('docs-site/content/docs/reference/', root);
const groups = new Map();

// Public workflow names keep the manual independent of internal transports.
function groupFor(name) {
  if (name.startsWith('reporting_')) return ['reporting', 'My Reports'];
  if (name.startsWith('backlink_audit_')) return ['backlink-audit', 'Backlink Audit'];
  if (name.startsWith('audit_web_vitals_')) return ['web-vitals', 'Core Web Vitals'];
  if (name.startsWith('audit_')) return ['site-audit', 'Site Audit'];
  if (name.startsWith('onpage_')) return ['on-page-seo-checker', 'On Page SEO Checker'];
  if (name.startsWith('position_')) return ['position-tracking', 'Position Tracking'];
  if (name.startsWith('saved_')) return ['saved-keywords', 'Saved Keywords'];
  if (name.startsWith('keyword_list') || name.startsWith('domain_strateg') || name === 'keyword_strategy_create') return ['keyword-lists', 'Keyword Strategy Builder'];
  if (name === 'keyword_gap' || name === 'backlink_gap') return ['comparisons', 'Domain comparisons'];
  if (name.startsWith('keyword_magic')) return ['keyword-magic', 'Keyword Magic'];
  if (name.startsWith('keyword_')) return ['keyword-research', 'Keyword research'];
  if (name.startsWith('domain_ai_') || name === 'ai_capabilities') return ['ai-visibility', 'AI visibility'];
  if (name.startsWith('domain_')) return ['organic-research', 'Organic Research'];
  if (name.startsWith('backlink')) return ['backlinks', 'Backlink Analytics'];
  if (name.startsWith('note')) return ['notes', 'Chart notes'];
  if (name.startsWith('project') || name === 'folders') return ['projects', 'Projects'];
  return ['account', 'Account and databases'];
}
const escape = value => String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('{', '&#123;').replaceAll('}', '&#125;').replaceAll('|', '&#124;').replaceAll('\n', ' ');
const frontmatter = title => ['---', `title: ${title}`, `description: Commands and options for ${title.toLowerCase()}.`, '---', '', '{/* Generated by npm run docs:generate from src/report-catalog.json. */}', ''];
for (const [name, definition] of Object.entries(catalog)) {
  const [slug, title] = groupFor(name);
  if (!groups.has(slug)) groups.set(slug, { title, commands: [] });
  groups.get(slug).commands.push([name, definition]);
}
const generatedFiles = new Map();
const index = ['---', 'title: Command reference', 'description: Find a command and its options.', '---', '',
  '{/* Generated by npm run docs:generate from src/report-catalog.json. */}', '',
  'Browse commands by workflow. For help in your terminal, run:', '', '```sh', 'semrush --help', 'semrush keyword-overview --help', 'semrush reports --json', '```', '',
  '| Workflow | Commands |', '| --- | --- |'];
for (const [slug, group] of groups) {
  index.push(`| [${group.title}](/docs/reference/${slug}) | ${group.commands.length} |`);
  const lines = frontmatter(group.title);
  for (const [name, definition] of group.commands) {
    const command = name.replaceAll('_', '-');
    lines.push(`## ${command}`, '', escape(definition.description), '', '```sh', `semrush ${command} --help`, '```', '', `MCP tool: \`${name}\`.`, '');
    if (definition.mutation) lines.push('Use `--confirm` to send the change or `--dry-run` to preview it.', '');
    if (['download', 'download_url', 'export_id', 'download_job', 'archive'].includes(definition.response_type)) lines.push('Pass `--output <path>` to save the file. Existing files are not overwritten. MCP returns an artifact resource.', '');
    const properties = Object.entries(definition.schema.properties);
    if (!properties.length) continue;
    lines.push('| Option | Type | Default | Description |', '| --- | --- | --- | --- |');
    for (const [key, property] of properties) {
      const type = property.type ?? property.anyOf?.map(candidate => candidate.type).join(' / ') ?? '';
      const fileInput = property.writeOnly === true || Boolean(property.contentMediaType);
      const defaultValue = property.default === undefined ? '' : '`' + escape(JSON.stringify(property.default)) + '`';
      const required = definition.schema.required?.includes(key) ? 'Required. ' : '';
      const choices = property.enum ? ' Values: ' + property.enum.map(value => '`' + escape(JSON.stringify(value)) + '`').join(', ') + '.' : '';
      lines.push(`| \`--${key.replaceAll('_', '-')}${fileInput ? '-file' : ''}\` | ${fileInput ? 'file or stdin' : escape(type)} | ${defaultValue} | ${required}${escape(property.description ?? '')}${choices} |`);
    }
    lines.push('');
  }
  generatedFiles.set(new URL(slug + '.mdx', reference), lines.join('\n').trimEnd() + '\n');
}
index.push('', 'CLI options use hyphens. MCP tool names and argument keys use underscores. Pass `--json` for compact JSON output.', '');
generatedFiles.set(new URL('docs-site/content/docs/reports.mdx', root), index.join('\n'));
generatedFiles.set(new URL('meta.json', reference), JSON.stringify({ title: 'Commands', pages: [...groups.keys()] }, null, 2) + '\n');
generatedFiles.set(new URL('docs-site/lib/operation-count.ts', root), '// Generated by npm run docs:generate from src/report-catalog.json.\nexport const operationCount = ' + Object.keys(catalog).length + ';\n');
if (!process.argv.includes('--check')) await mkdir(reference, { recursive: true });
for (const [path, generated] of generatedFiles) {
  if (process.argv.includes('--check')) {
    const actual = await readFile(path, 'utf8').catch(error => { if (error.code === 'ENOENT') return ''; throw error; });
    if (actual !== generated) { process.stderr.write('Command documentation is stale: ' + path.pathname + '\nRun npm run docs:generate.\n'); process.exitCode = 1; }
  } else await writeFile(path, generated);
}
